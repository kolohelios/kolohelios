//! Integration tests for `shaka ci generate-workflows` and
//! `shaka ci audit-workflows`.
//!
//! Both subcommands `cue export` every discovered `project.cue` and
//! touch `.github/workflows/`, so they need a real temp repo with a
//! `cue.mod` (planted by `common::write_test_module`) and at least one
//! project carrying a `ci.build` block. We stage `apps/widget` from
//! `tests/fixtures/ci-generate/`, then drive the binary against that
//! tempdir as cwd — exit code plus the on-disk workflow file are the
//! contract.

use std::path::{Path, PathBuf};
use std::process::Command;

mod common;

const SHAKA_BIN: &str = env!("CARGO_BIN_EXE_shaka");

fn fixtures_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/ci-generate")
}

/// Stage `apps/widget` (a buildable rust-cli) into a fresh temp repo
/// with a resolvable cue module, returning the repo root.
fn staged_repo() -> tempfile::TempDir {
    let root = tempfile::TempDir::new().unwrap();
    common::write_test_module(root.path());

    let dst = root.path().join("apps/widget");
    std::fs::create_dir_all(&dst).unwrap();
    // The fixture carries a `.fixture` suffix so the source tree never
    // holds a stray `project.cue` (rejected by schema-check, #95).
    std::fs::copy(
        fixtures_root().join("widget/project.cue.fixture"),
        dst.join("project.cue"),
    )
    .unwrap();

    root
}

/// No tools/shaka tree or publishing block: just an external consumer project.
fn standalone_repo() -> tempfile::TempDir {
    let root = tempfile::TempDir::new().unwrap();
    common::write_test_module(root.path());
    // Exercise the packaged-schema fallback, not a local domain registry.
    std::fs::remove_dir_all(root.path().join("infra")).unwrap();
    let dst = root.path().join("projects/standalone");
    std::fs::create_dir_all(&dst).unwrap();
    std::fs::copy(
        fixtures_root().join("standalone/project.cue.fixture"),
        dst.join("project.cue"),
    )
    .unwrap();
    root
}

fn run(root: &Path, args: &[&str]) -> std::process::Output {
    Command::new(SHAKA_BIN)
        .args(args)
        .current_dir(root)
        .output()
        .expect("spawn shaka")
}

#[test]
fn standalone_validation_round_trips_and_passes_actionlint() {
    let repo = standalone_repo();
    for args in [
        vec!["project", "schema-check"],
        vec!["ci", "generate-workflows"],
        vec!["ci", "generate-workflows", "--check"],
        vec!["ci", "audit-workflows"],
    ] {
        let out = run(repo.path(), &args);
        assert!(
            out.status.success(),
            "{args:?}: {}{}",
            String::from_utf8_lossy(&out.stdout),
            String::from_utf8_lossy(&out.stderr)
        );
    }
    let path = repo
        .path()
        .join(".github/workflows/standalone-validate.yml");
    let content = std::fs::read_to_string(&path).unwrap();
    let workflow: serde_yaml_ng::Value = serde_yaml_ng::from_str(&content).unwrap();
    assert!(content.starts_with("# Generated by shaka."));
    assert!(!content.contains("tools/shaka"));
    assert!(!content.contains("secrets."));
    assert!(!content.contains("publish"));
    assert!(!repo.path().join(".github/workflows/main.yaml").exists());
    assert!(workflow["on"]
        .as_mapping()
        .unwrap()
        .contains_key("pull_request"));
    assert!(workflow["on"]["pull_request"].is_null());
    assert!(workflow["on"]["push"]["paths"].is_null());
    assert_eq!(workflow["on"]["push"]["branches"][0], "main");
    assert_eq!(workflow["permissions"]["contents"], "read");
    assert_eq!(workflow["permissions"]["id-token"], "write");
    assert_eq!(workflow["jobs"]["validate"]["name"], "standalone validate");
    assert!(workflow["jobs"]["validate"]["if"].is_null());
    let steps = workflow["jobs"]["validate"]["steps"].as_sequence().unwrap();
    assert_eq!(steps[0]["with"]["fetch-depth"], 0);
    let commands: Vec<&str> = steps.iter().filter_map(|s| s["run"].as_str()).collect();
    assert!(commands
        .iter()
        .all(|c| c.starts_with("nix develop './projects/standalone' --command ")));
    assert!(commands
        .iter()
        .any(|c| c.ends_with("jj git init --colocate")));
    assert!(commands.iter().any(|c| c.ends_with("shaka preflight")));
    assert!(!content.contains("--since"));
    let lint = Command::new("actionlint")
        .arg(&path)
        .output()
        .expect("spawn actionlint");
    assert!(
        lint.status.success(),
        "{}{}",
        String::from_utf8_lossy(&lint.stdout),
        String::from_utf8_lossy(&lint.stderr)
    );
}

#[test]
fn standalone_validation_detects_drift_and_missing_output() {
    let repo = standalone_repo();
    assert!(run(repo.path(), &["ci", "generate-workflows"])
        .status
        .success());
    let path = repo
        .path()
        .join(".github/workflows/standalone-validate.yml");
    let mut content = std::fs::read_to_string(&path).unwrap();
    content.push_str("# manual edit\n");
    std::fs::write(&path, content).unwrap();
    assert!(!run(repo.path(), &["ci", "generate-workflows", "--check"])
        .status
        .success());
    std::fs::remove_file(path).unwrap();
    assert!(!run(repo.path(), &["ci", "generate-workflows", "--check"])
        .status
        .success());
}

#[test]
fn standalone_validation_does_not_allow_unrelated_workflows() {
    let repo = standalone_repo();
    assert!(run(repo.path(), &["ci", "generate-workflows"])
        .status
        .success());
    std::fs::copy(
        repo.path()
            .join(".github/workflows/standalone-validate.yml"),
        repo.path().join(".github/workflows/handwritten.yml"),
    )
    .unwrap();
    assert!(!run(repo.path(), &["ci", "audit-workflows"])
        .status
        .success());
}

#[test]
fn generate_workflows_emits_main_yaml_for_a_build_project() {
    let repo = staged_repo();
    let out = run(repo.path(), &["ci", "generate-workflows"]);
    assert!(
        out.status.success(),
        "generate-workflows failed: {}",
        String::from_utf8_lossy(&out.stderr)
    );

    let main_yaml = repo.path().join(".github/workflows/main.yaml");
    let content = std::fs::read_to_string(&main_yaml).expect("main.yaml written");
    // The widget's ci.build block becomes a `build-widget` job that
    // publishes to its declared FlakeHub name.
    assert!(content.contains("build-widget:"), "{content}");
    assert!(content.contains("kolohelios/widget"), "{content}");
}

#[test]
fn generate_workflows_check_passes_after_generating() {
    let repo = staged_repo();
    // First write, then `--check` must agree byte-for-byte.
    assert!(run(repo.path(), &["ci", "generate-workflows"])
        .status
        .success());
    let out = run(repo.path(), &["ci", "generate-workflows", "--check"]);
    assert!(
        out.status.success(),
        "--check drifted right after generate: {}",
        String::from_utf8_lossy(&out.stderr)
    );
}

#[test]
fn generate_workflows_check_detects_drift() {
    let repo = staged_repo();
    assert!(run(repo.path(), &["ci", "generate-workflows"])
        .status
        .success());
    // Corrupt the generated file; `--check` must now fail.
    let main_yaml = repo.path().join(".github/workflows/main.yaml");
    std::fs::write(&main_yaml, "name: tampered\n").unwrap();
    let out = run(repo.path(), &["ci", "generate-workflows", "--check"]);
    assert!(!out.status.success(), "drift should fail --check");
    let combined = format!(
        "{}{}",
        String::from_utf8_lossy(&out.stdout),
        String::from_utf8_lossy(&out.stderr)
    );
    assert!(
        combined.contains("DRIFT") || combined.contains("drifted"),
        "{combined}"
    );
}

#[test]
fn audit_workflows_accepts_a_generated_main_yaml() {
    let repo = staged_repo();
    assert!(run(repo.path(), &["ci", "generate-workflows"])
        .status
        .success());
    let out = run(repo.path(), &["ci", "audit-workflows"]);
    assert!(
        out.status.success(),
        "audit-workflows rejected a generated file: {}",
        String::from_utf8_lossy(&out.stderr)
    );
}

#[test]
fn audit_workflows_flags_an_unaccounted_workflow() {
    let repo = staged_repo();
    let wf_dir = repo.path().join(".github/workflows");
    std::fs::create_dir_all(&wf_dir).unwrap();
    // A hand-dropped workflow that is neither generated nor allowlisted.
    std::fs::write(wf_dir.join("rogue.yml"), "name: rogue\n").unwrap();
    let out = run(repo.path(), &["ci", "audit-workflows"]);
    assert!(
        !out.status.success(),
        "rogue workflow should fail the audit"
    );
    let combined = format!(
        "{}{}",
        String::from_utf8_lossy(&out.stdout),
        String::from_utf8_lossy(&out.stderr)
    );
    assert!(combined.contains("rogue.yml"), "{combined}");
}
