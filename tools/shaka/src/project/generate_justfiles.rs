/// The subset of `cargo metadata --no-deps` output used to detect a virtual
/// workspace and classify its members (worker cdylib vs. consumable libs).
#[derive(Deserialize)]
struct CargoMetadata {
    packages: Vec<CargoPackage>,
}

#[derive(Deserialize)]
struct CargoPackage {
    name: String,
    manifest_path: String,
    #[serde(default)]
    targets: Vec<CargoTarget>,
}

#[derive(Deserialize)]
struct CargoTarget {
    #[serde(default)]
    crate_types: Vec<String>,
}

impl CargoPackage {
    /// Whether any target builds a `cdylib` — the signal for the worker crate
    /// (`worker-build` links the cdylib).
    fn is_cdylib(&self) -> bool {
        self.targets
            .iter()
            .any(|t| t.crate_types.iter().any(|c| c == "cdylib"))
    }

    /// Whether any target builds a plain Rust library (`lib`/`rlib`) — the
    /// signal for a wasm-consumable member checked by `wasm-check`. A
    /// cdylib-only crate (e.g. a browser-wasm or FFI member) or a bin-only
    /// crate has no such target and is excluded.
    fn is_rust_lib(&self) -> bool {
        self.targets
            .iter()
            .any(|t| t.crate_types.iter().any(|c| c == "lib" || c == "rlib"))
    }
}

/// The justification if this project waives `justfile` generation via
/// `generate.skip`, else `None`. A waived project is excluded from both the
/// write pass and the `--check` drift pass — the interim escape hatch (#924)
/// for a hand-maintained rust-worker workspace justfile until #922 lands
/// workspace-aware generation.
fn waived_justfile(meta: &ProjectMeta) -> Option<&str> {
    meta.generate
        .as_ref()?
        .skip
        .iter()
        .find(|s| s.step == "justfile")
        .map(|s| s.reason.as_str())
}

pub fn run(check: bool) {
    if let Err(e) = schema_check::project_schema_path() {
        eprintln!("{RED}{BOLD}error:{RESET} could not resolve project schema: {e}");
        std::process::exit(1);
    }

    let mut items: Vec<(PathBuf, String)> = Vec::new();

    let projects = discover_projects(Path::new("."));
    for project in &projects {
        match read_meta(project) {
            Ok(meta) => {
                // native-app is host-built (iOS/Android): the platform
                // build runs in Xcode/Gradle, not `just validate`, so
                // shaka emits no justfile for it. Skip rather than error
                // like a genuinely unknown kind — this absence is by
                // design. (#941)
                if meta.kind == "native-app" {
                    continue;
                }
                if let Some(reason) = waived_justfile(&meta) {
                    println!(
                        "  {YELLOW}{BOLD}WAIVED{RESET}   {} {DIM}({reason}){RESET}",
                        project.join("justfile").display()
                    );
                    continue;
                }
                match template_for(&meta.kind, project) {
                    Some(body) => items.push((project.join("justfile"), render(&body))),
                    None => {
                        eprintln!(
                            "{RED}{BOLD}error:{RESET} {} has unknown kind {:?}",
                            project.display(),
                            meta.kind
                        );
                        std::process::exit(1);
                    }
                }
            }
            Err(e) => {
                eprintln!(
                    "{RED}{BOLD}error:{RESET} could not read {}: {e}",
                    project.display()
                );
                std::process::exit(1);
            }
        }
    }

    if check {
        check_drift(&items);
    } else {
        write_all(&items);
    }
}

fn template_for(kind: &str, project_dir: &Path) -> Option<String> {
    match kind {
        "rust-cli" => Some(
            // A `data/schema.cue` signals the project ships typed CUE
            // data (e.g. `aof`'s areas-of-focus tree) that
            // `shaka project schema-check` doesn't cover — it validates
            // `project.cue`, not arbitrary data. Add a `cue-vet` recipe
            // that vets the whole `data/` package and fold it into
            // `validate` so a malformed `data/*.cue` fails locally and
            // in CI.
            if project_dir.join("data/schema.cue").is_file() {
                rust_cli_with_data_vet()
            } else {
                RUST_TEMPLATE.to_string()
            },
        ),
        "rust-worker" => Some(rust_worker_body(project_dir)),
        "infra" => Some(
            if project_dir.join("terraform").is_dir() {
                // `.env.example` signals the project resolves secrets via
                // `op run --env-file=.env`; absence means tfvars/env-set
                // credentials (see `infra/devbox`).
                if project_dir.join(".env.example").is_file() {
                    INFRA_TEMPLATE_WITH_TF
                } else {
                    INFRA_TEMPLATE_WITH_TF_BARE
                }
            } else {
                INFRA_TEMPLATE_NO_TF
            }
            .to_string(),
        ),
        "rust-lib" => Some(RUST_LIB_TEMPLATE.to_string()),
        "wasm-app" => Some(WASM_APP_TEMPLATE.to_string()),
        "nix-lib" => Some(NIX_LIB_TEMPLATE.to_string()),
        "document" => Some(DOCUMENT_TEMPLATE.to_string()),
        _ => None,
    }
}

/// The justfile body for a `rust-worker` project. A virtual Cargo workspace
/// (members under `crates/`, no root `[package]`) gets the workspace template
/// with crate-scoped recipes; a single-crate worker keeps the flat template
/// (plus the `build-site` variant when it ships a static-site generator).
///
/// Workspace detection falls back to the single-crate template if `cargo
/// metadata` can't be read or the layout isn't the expected one-cdylib shape —
/// generation stays best-effort rather than failing the whole run.
fn rust_worker_body(project_dir: &Path) -> String {
    if let Some(layout) = workspace_layout(project_dir) {
        return rust_worker_workspace(&layout);
    }
    // `src/bin/build-site.rs` signals a static-site build pipeline (templates +
    // tailwind → committed `dist/`). Add a `build-check` recipe that re-runs the
    // pipeline and diffs against committed output, folded into `validate` so CI
    // catches drift.
    if project_dir.join("src/bin/build-site.rs").is_file() {
        rust_worker_with_build_site()
    } else {
        RUST_WORKER_TEMPLATE.to_string()
    }
}

/// A `rust-worker` virtual-workspace layout: the wasm-consumable library members
/// (everything that isn't the worker) and the worker crate's directory relative
/// to the project root.
struct WorkspaceLayout {
    /// Package names of the non-worker library members, in `cargo metadata`
    /// order, used as `-p <name>` flags on `wasm-check`.
    lib_pkgs: Vec<String>,
    /// The worker (cdylib) crate's directory, relative to the project root —
    /// where `worker-build` runs (e.g. `crates/buzzingo-server`).
    worker_dir: String,
}

/// Inspect `project_dir` via `cargo metadata` and, if it is a virtual workspace
/// with exactly one cdylib (worker) member, return its [`WorkspaceLayout`].
/// Returns `None` for a single-crate package, a non-Cargo project, an
/// unreadable/failed `cargo metadata`, or any layout that isn't the expected
/// one-worker shape — callers fall back to the single-crate template.
fn workspace_layout(project_dir: &Path) -> Option<WorkspaceLayout> {
    let manifest = project_dir.join("Cargo.toml");
    if !manifest.is_file() {
        return None;
    }
    let output = std::process::Command::new("cargo")
        .args(["metadata", "--no-deps", "--format-version", "1"])
        .arg("--manifest-path")
        .arg(&manifest)
        .output()
        .ok()?;
    if !output.status.success() {
        return None;
    }
    let meta: CargoMetadata = serde_json::from_slice(&output.stdout).ok()?;

    // Canonicalize both sides before comparing paths: `cargo metadata` resolves
    // symlinks in `manifest_path` (e.g. macOS `/var` → `/private/var`), so the
    // project root must be resolved too or none of the prefix/equality checks
    // below would match.
    let root_dir = std::fs::canonicalize(project_dir).ok()?;
    let root_manifest = root_dir.join("Cargo.toml");

    // A virtual workspace has no root package: no member's manifest is the root
    // Cargo.toml. A single-crate package is left to the flat template.
    let is_virtual = !meta
        .packages
        .iter()
        .any(|p| std::fs::canonicalize(&p.manifest_path).is_ok_and(|m| m == root_manifest));
    if !is_virtual {
        return None;
    }

    // Identify the worker among the cdylib members. With a single cdylib it's
    // unambiguous; with several (e.g. a worker plus browser-wasm/FFI cdylibs)
    // the worker is the one the project's `wrangler.toml` `main` shim points
    // at — `worker-build` runs in that crate's dir, so `main` carries its path
    // prefix. Bail to the flat template if there's no cdylib or the multiple
    // can't be disambiguated.
    let cdylibs: Vec<&CargoPackage> = meta.packages.iter().filter(|p| p.is_cdylib()).collect();
    let worker = match cdylibs.as_slice() {
        [only] => *only,
        [] => return None,
        _ => disambiguate_worker(project_dir, &root_dir, &cdylibs)?,
    };

    let worker_dir = relative_crate_dir(&root_dir, &worker.manifest_path)?;

    // The wasm-checked members are the wasm-consumable libraries — members
    // that produce a Rust `lib`/`rlib` — excluding the worker itself (its wasm
    // build is covered by `worker-build-check`). Cdylib-only and bin-only
    // members drop out.
    let lib_pkgs: Vec<String> = meta
        .packages
        .iter()
        .filter(|p| p.name != worker.name && p.is_rust_lib())
        .map(|p| p.name.clone())
        .collect();
    if lib_pkgs.is_empty() {
        return None;
    }
    Some(WorkspaceLayout {
        lib_pkgs,
        worker_dir,
    })
}

/// Pick the worker among several cdylib members by matching the project's
/// `wrangler.toml` `main` path against each member's directory: the worker is
/// the cdylib whose crate dir prefixes `main` (e.g.
/// `main = "crates/foo-server/build/worker/shim.mjs"` → `crates/foo-server`).
/// Returns `None` if there's no readable `wrangler.toml`, no `main`, or no
/// unambiguous match — callers fall back to the flat template.
fn disambiguate_worker<'a>(
    project_dir: &Path,
    root_dir: &Path,
    cdylibs: &[&'a CargoPackage],
) -> Option<&'a CargoPackage> {
    let main = wrangler_main(project_dir)?;
    cdylibs.iter().copied().find(|p| {
        relative_crate_dir(root_dir, &p.manifest_path)
            .is_some_and(|dir| !dir.is_empty() && path_has_prefix(&main, &dir))
    })
}

/// Read the top-level `main = "..."` value from `<project_dir>/wrangler.toml`.
/// A line scan (stopping at the first table header) is enough: shaka's
/// generated `wrangler.toml` declares `main` as a top-level key, and `main`
/// isn't a valid key inside any of the tables that follow.
fn wrangler_main(project_dir: &Path) -> Option<String> {
    let contents = std::fs::read_to_string(project_dir.join("wrangler.toml")).ok()?;
    for line in contents.lines() {
        let trimmed = line.trim();
        if trimmed.starts_with('[') {
            break;
        }
        if let Some(rest) = trimmed.strip_prefix("main") {
            let rest = rest.trim_start();
            if let Some(value) = rest.strip_prefix('=') {
                return Some(value.trim().trim_matches(['"', '\'']).to_string());
            }
        }
    }
    None
}

/// Whether `path` equals `prefix` or begins with `prefix/` — a path-segment
/// prefix test, so `crates/foo` matches `crates/foo/...` but not
/// `crates/foobar`.
fn path_has_prefix(path: &str, prefix: &str) -> bool {
    path == prefix
        || path
            .strip_prefix(prefix)
            .is_some_and(|r| r.starts_with('/'))
}

/// The directory of `manifest_path` (a member's `Cargo.toml`) relative to the
/// canonicalized project root `root_dir`, with forward slashes — e.g.
/// `crates/buzzingo-server`. Both sides are canonicalized so symlinked roots
/// (macOS tempdirs) still strip cleanly.
fn relative_crate_dir(root_dir: &Path, manifest_path: &str) -> Option<String> {
    let crate_dir = std::fs::canonicalize(Path::new(manifest_path).parent()?).ok()?;
    let rel = crate_dir.strip_prefix(root_dir).ok()?;
    Some(rel.to_string_lossy().replace('\\', "/"))
}

/// Render [`RUST_WORKER_WORKSPACE_TEMPLATE`] for a discovered workspace layout,
/// substituting the `-p <lib>` flags and the worker crate directory.
fn rust_worker_workspace(layout: &WorkspaceLayout) -> String {
    let lib_pkgs = layout
        .lib_pkgs
        .iter()
        .map(|p| format!("-p {p}"))
        .collect::<Vec<_>>()
        .join(" ");
    RUST_WORKER_WORKSPACE_TEMPLATE
        .replace("{LIB_PKGS}", &lib_pkgs)
        .replace("{WORKER_DIR}", &layout.worker_dir)
}

/// `RUST_WORKER_TEMPLATE` with the `build-check` recipe prepended and
/// the recipe added as a dependency of `validate`. Used when a
/// rust-worker project ships a `src/bin/build-site.rs` static-site
/// generator alongside the worker.
fn rust_worker_with_build_site() -> String {
    let mut body = RUST_WORKER_BUILD_CHECK_RECIPE.to_string();
    body.push_str(&RUST_WORKER_TEMPLATE.replace(
        "validate: fmt-check lint",
        "validate: build-check fmt-check lint",
    ));
    body
}

/// `RUST_TEMPLATE` with the `cue-vet` recipe prepended and the recipe
/// added as a dependency of `validate`. Used when a rust-cli project
/// ships typed CUE data under `data/` (marked by `data/schema.cue`).
fn rust_cli_with_data_vet() -> String {
    let mut body = RUST_CLI_DATA_VET_RECIPE.to_string();
    body.push_str(&RUST_TEMPLATE.replace(
        "validate: fmt-check lint",
        "validate: cue-vet fmt-check lint",
    ));
    body
}

const RUST_CLI_DATA_VET_RECIPE: &str = r#"# Vet typed CUE data under `data/` against its schema. Unlike
# `shaka project schema-check` (which validates `project.cue`), this
# gates arbitrary `data/*.cue` so a malformed data file fails here
# rather than at runtime.
cue-vet:
    cue vet ./data/...

"#;

const RUST_WORKER_BUILD_CHECK_RECIPE: &str = r#"# Drift check for the static-asset build pipeline. Re-runs the same
# render-and-tailwind pipeline that produces committed `dist/`, into
# a temp directory, and diffs against `dist/`. Forces a regenerate-
# and-commit when templates, data, or styles change so CI can't
# silently deploy a `dist/` that doesn't match its sources.
build-check:
    cargo run --quiet --features build-site --bin build-site -- --check

"#;

fn render(body: &str) -> String {
    format!("{HEADER}{body}")
}

fn write_all(items: &[(PathBuf, String)]) {
    for (path, content) in items {
        if let Err(e) = std::fs::write(path, content) {
            eprintln!("{RED}{BOLD}error:{RESET} writing {}: {e}", path.display());
            std::process::exit(1);
        }
        println!("  {GREEN}{BOLD}wrote{RESET}    {}", path.display());
    }
    println!(
        "\n{GREEN}{BOLD}generate-justfiles:{RESET} wrote {} files",
        items.len()
    );
}

fn check_drift(items: &[(PathBuf, String)]) {
    let mut drift = Vec::new();
    for (path, expected) in items {
        match std::fs::read_to_string(path) {
            Ok(actual) if actual == *expected => {
                println!("  {GREEN}{BOLD}ok{RESET}       {}", path.display());
            }
            Ok(_) => {
                println!("  {RED}{BOLD}DRIFT{RESET}    {}", path.display());
                drift.push(path.clone());
            }
            Err(_) => {
                println!("  {RED}{BOLD}MISSING{RESET}  {}", path.display());
                drift.push(path.clone());
            }
        }
    }
    println!();
    if !drift.is_empty() {
        eprintln!(
            "{RED}{BOLD}generate-justfiles --check failed{RESET}: {} file(s) drifted",
            drift.len()
        );
        eprintln!("{YELLOW}Run `shaka project generate-justfiles` and commit the result.{RESET}");
        eprintln!(
            "{DIM}drifted: {}{RESET}",
            drift
                .iter()
                .map(|p| p.display().to_string())
                .collect::<Vec<_>>()
                .join(", ")
        );
        std::process::exit(1);
    }
    println!("{GREEN}{BOLD}generate-justfiles --check passed{RESET}");
}

fn discover_projects(root: &Path) -> Vec<PathBuf> {
    let mut projects = Vec::new();
    for slot in SLOTS {
        let slot_dir = root.join(slot);
        let entries = match std::fs::read_dir(&slot_dir) {
            Ok(e) => e,
            Err(_) => continue,
        };
        for entry in entries.flatten() {
            let path = entry.path();
            if path.is_dir() {
                projects.push(path);
            }
        }
    }
    projects.sort();
    projects
}

fn read_meta(project_dir: &Path) -> Result<ProjectMeta, String> {
    let project_file = project_dir.join("project.cue");
    if !project_file.exists() {
        return Err("missing project.cue".into());
    }

    let output = schema_check::cue_project(&["export"], &project_file)
        .map_err(|e| format!("failed to spawn cue: {e}"))?;

    if !output.status.success() {
        let stderr = String::from_utf8_lossy(&output.stderr).trim().to_string();
        return Err(format!("cue export failed: {stderr}"));
    }

    serde_json::from_slice::<ProjectMeta>(&output.stdout)
        .map_err(|e| format!("could not parse cue export output: {e}"))
}

