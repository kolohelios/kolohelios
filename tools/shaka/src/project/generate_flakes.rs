/// Compose an infra flake. Standard shape: kolohelios-nix + nixpkgs
/// inputs (plus any `extra_inputs`), `let .. in` that inherits
/// `forEachSupportedSystem` + `workflowPackages` from the shared lib,
/// devshell composed from `workflowPackages` ++ `dev_shell_packages`.
/// The optional `extra` raw-nix snippet is inserted after devShells
/// (so project-specific outputs like devbox's `nixosConfigurations`
/// or home's `darwinConfigurations` can be tacked on without
/// requiring per-project carve-outs in the generator).
fn render_infra_flake(name: &str, infra: &InfraMeta) -> String {
    let description = infra.description.as_deref().unwrap_or(name);
    let mut out = String::with_capacity(1024);
    out.push_str(HEADER);
    out.push_str(&format!("{{\n  description = \"{description}\";\n\n"));
    out.push_str("  inputs = {\n");
    out.push_str(
        r#"    kolohelios-nix.url = "https://flakehub.com/f/kolohelios/kolohelios-nix/*.tar.gz";"#,
    );
    out.push('\n');
    out.push_str(r#"    nixpkgs.follows = "kolohelios-nix/nixpkgs";"#);
    out.push('\n');
    for (input_name, spec) in &infra.extra_inputs {
        out.push_str(&render_extra_input(input_name, spec));
    }
    out.push_str("  };\n");
    out.push_str("\n  outputs =\n    {\n      self,\n      kolohelios-nix,\n      nixpkgs,\n");
    for input_name in infra.extra_inputs.keys() {
        out.push_str(&format!("      {input_name},\n"));
    }
    out.push_str("      ...\n    }:\n    let\n");
    out.push_str("      inherit (kolohelios-nix.lib) forEachSupportedSystem workflowPackages;\n");
    if let Some(let_extra) = &infra.let_extra {
        out.push('\n');
        out.push_str(let_extra.trim_end());
        out.push('\n');
    }
    out.push_str("    in\n    {\n");
    out.push_str(&render_infra_devshell(&infra.dev_shell_packages));
    if let Some(extra) = &infra.extra {
        out.push('\n');
        out.push_str(extra.trim_end());
        out.push('\n');
    }
    out.push_str("\n      formatter = kolohelios-nix.formatter;\n    };\n");
    out.push_str("}\n");
    out
}

/// Render one entry of `inputs = { ... }` for an `extra_inputs` map
/// entry. Single-key (no follows) collapses to `name.url = "...";`;
/// multi-key uses an attrset.
fn render_extra_input(name: &str, spec: &ExtraInput) -> String {
    if spec.follows.is_empty() {
        return format!("    {name}.url = \"{}\";\n", spec.url);
    }
    let mut out = format!("    {name} = {{\n");
    out.push_str(&format!("      url = \"{}\";\n", spec.url));
    for (src, dest) in &spec.follows {
        out.push_str(&format!("      inputs.{src}.follows = \"{dest}\";\n"));
    }
    out.push_str("    };\n");
    out
}

/// Devshell block for infra flakes. `packages` is `(workflowPackages
/// pkgs) ++ [pkgs.X pkgs.Y ...]`. Empty `dev_shell_packages` collapses
/// to just `workflowPackages pkgs` so home's devshell stays minimal.
fn render_infra_devshell(dev_shell_packages: &[String]) -> String {
    let mut out = String::new();
    out.push_str("      devShells = forEachSupportedSystem (\n");
    out.push_str("        { pkgs, ... }:\n");
    out.push_str("        {\n");
    out.push_str("          default = pkgs.mkShell {\n");
    if dev_shell_packages.is_empty() {
        out.push_str("            packages = workflowPackages pkgs;\n");
    } else {
        out.push_str("            packages =\n");
        out.push_str("              (workflowPackages pkgs)\n");
        out.push_str("              ++ (with pkgs; [\n");
        for pkg in dev_shell_packages {
            out.push_str(&format!("                {pkg}\n"));
        }
        out.push_str("              ]);\n");
    }
    out.push_str("          };\n        }\n      );\n");
    out
}

/// Compose a nix-lib flake. The template provides only the
/// "Do not edit by hand" header, description, `nixpkgs` input, and
/// outputs signature; the entire `let .. in { ... }` body lives in
/// `nl.extra` because nix-lib defines what other flakes import, so its
/// shape isn't a fixed template. Drift checking still applies — every
/// hand-edit shows up as a `--check` failure.
fn render_nix_lib_flake(name: &str, nl: &NixLibMeta) -> String {
    let description = nl.description.as_deref().unwrap_or(name);
    let mut out = String::with_capacity(1024);
    out.push_str(HEADER);
    out.push_str(&format!("{{\n  description = \"{description}\";\n\n"));
    out.push_str("  inputs.nixpkgs.url = \"https://flakehub.com/f/NixOS/nixpkgs/0\";\n");
    out.push_str("\n  outputs =\n");
    out.push_str("    { self, nixpkgs, ... }:\n");
    if let Some(extra) = &nl.extra {
        out.push_str(extra.trim_end());
        out.push('\n');
    }
    out.push_str("}\n");
    out
}

/// Renders a nixpkgs-attr list as `attr = [ pkgs.A pkgs.B ];` or, when
/// it has a single entry, as a single-line `[ pkgs.X ]`. `indent` is
/// the column at which the attribute line starts (used to indent the
/// closing bracket).
fn render_pkg_list(attr: &str, items: &[String], indent: usize) -> String {
    let pad = " ".repeat(indent);
    if items.len() == 1 {
        return format!("{pad}{attr} = [ pkgs.{} ];\n", items[0]);
    }
    let mut out = format!("{pad}{attr} = [\n");
    for item in items {
        out.push_str(&format!("{pad}  pkgs.{item}\n"));
    }
    out.push_str(&format!("{pad}];\n"));
    out
}

fn read_meta(project_dir: &Path) -> Result<ProjectMeta, String> {
    let project_file = project_dir.join("project.cue");
    if !project_file.exists() {
        return Err("missing project.cue".into());
    }

    let output = schema_check::cue_project(&["export"], &project_file)
        .map_err(|e| format!("failed to spawn cue: {e}"))?;

    if !output.status.success() {
        let stderr = String::from_utf8_lossy(&output.stderr).trim().to_string();
        return Err(format!("cue export failed: {stderr}"));
    }

    serde_json::from_slice::<ProjectMeta>(&output.stdout)
        .map_err(|e| format!("could not parse cue export output: {e}"))
}

fn write_all(items: &[(PathBuf, String)]) {
    for (path, content) in items {
        if let Err(e) = std::fs::write(path, content) {
            eprintln!("{RED}{BOLD}error:{RESET} writing {}: {e}", path.display());
            std::process::exit(1);
        }
        println!("  {GREEN}{BOLD}wrote{RESET}    {}", path.display());
    }
    println!(
        "\n{GREEN}{BOLD}generate-flakes:{RESET} wrote {} files",
        items.len()
    );
}

fn check_drift(items: &[(PathBuf, String)]) {
    let mut drift = Vec::new();
    for (path, expected) in items {
        match std::fs::read_to_string(path) {
            Ok(actual) if actual == *expected => {
                println!("  {GREEN}{BOLD}ok{RESET}       {}", path.display());
            }
            Ok(_) => {
                println!("  {RED}{BOLD}DRIFT{RESET}    {}", path.display());
                drift.push(path.clone());
            }
            Err(_) => {
                println!("  {RED}{BOLD}MISSING{RESET}  {}", path.display());
                drift.push(path.clone());
            }
        }
    }
    println!();
    if !drift.is_empty() {
        eprintln!(
            "{RED}{BOLD}generate-flakes --check failed{RESET}: {} file(s) drifted",
            drift.len()
        );
        eprintln!("{YELLOW}Run `shaka project generate-flakes` and commit the result.{RESET}");
        eprintln!(
            "{DIM}drifted: {}{RESET}",
            drift
                .iter()
                .map(|p| p.display().to_string())
                .collect::<Vec<_>>()
                .join(", ")
        );
        std::process::exit(1);
    }
    println!("{GREEN}{BOLD}generate-flakes --check passed{RESET}");
}

