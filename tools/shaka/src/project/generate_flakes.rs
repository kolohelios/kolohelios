fn render_packages(cli: &CliMeta) -> String {
    let bin = &cli.binary_name;
    let mut out = String::new();
    out.push_str("      packages = forEachSupportedSystem (\n");
    out.push_str("        { pkgs, ... }:\n");
    out.push_str("        {\n");
    out.push_str("          default = (rustPlatform pkgs).buildRustPackage {\n");
    out.push_str(&format!("            pname = \"{bin}\";\n"));
    out.push_str("            version = \"0.1.0\";\n");
    out.push_str("            src = ./.;\n");
    out.push_str("            cargoLock.lockFile = ./Cargo.lock;\n");

    if !cli.check_inputs.is_empty() {
        out.push_str(&render_pkg_list("nativeCheckInputs", &cli.check_inputs, 12));
    }

    // jj 0.30+ (nixpkgs 26.05) writes a per-repo "secure config" under
    // `$HOME/.config/jj/repos/`, so `jj config set --repo` aborts when
    // HOME is unwritable. The build sandbox sets HOME=/homeless-shelter,
    // so any project whose tests drive jj needs a writable HOME for the
    // check phase. Scoped to jj-using projects via the `jujutsu` check
    // input rather than emitted unconditionally.
    if cli.check_inputs.iter().any(|i| i == "jujutsu") {
        out.push_str(
            "            preCheck = ''\n              export HOME=\"$(mktemp -d)\"\n            '';\n",
        );
    }

    // `wrapProgram` (from makeWrapper) is needed for a PATH prefix and/or
    // the SHAKA_CUE_MODULE_DIR set, so either knob pulls it in.
    let needs_wrapper = !cli.runtime_path_deps.is_empty() || cli.cue_module.is_some();
    let mut native_build_inputs: Vec<String> = Vec::new();
    if needs_wrapper {
        native_build_inputs.push("makeWrapper".to_string());
    }
    if cli.shell_completions {
        native_build_inputs.push("installShellFiles".to_string());
    }
    if !native_build_inputs.is_empty() {
        out.push_str(&render_pkg_list(
            "nativeBuildInputs",
            &native_build_inputs,
            12,
        ));
    }

    if cli.shell_completions || cli.cue_module.is_some() {
        out.push_str("            postInstall = ''\n");
        if cli.shell_completions {
            out.push_str(&format!(
                "              installShellCompletion --cmd {bin} \\\n                --bash <($out/bin/{bin} completions bash) \\\n                --fish <($out/bin/{bin} completions fish) \\\n                --zsh  <($out/bin/{bin} completions zsh)\n"
            ));
        }
        if let Some(cue) = &cli.cue_module {
            if cli.shell_completions {
                out.push('\n');
            }
            out.push_str(
                "              # Bundle the CUE module closure so schema-dependent\n              # subcommands resolve the schema + registry from a packaged\n              # binary run outside the monorepo (SHAKA_CUE_MODULE_DIR; see\n              # tools/shaka/src/project/schema_check.rs).\n",
            );
            for inc in &cue.include {
                let dest = if inc.to == "." {
                    CUE_BUNDLE_DIR.to_string()
                } else {
                    format!("{CUE_BUNDLE_DIR}/{}", inc.to)
                };
                out.push_str(&format!(
                    "              mkdir -p {dest}\n              cp -r {}/. {dest}/\n",
                    inc.from
                ));
            }
        }
        out.push_str("            '';\n");
    }

    if needs_wrapper {
        out.push_str(&format!(
            "            postFixup = ''\n              wrapProgram $out/bin/{bin}"
        ));
        if !cli.runtime_path_deps.is_empty() {
            out.push_str(" \\\n                --prefix PATH : ${\n                  pkgs.lib.makeBinPath [\n");
            for dep in &cli.runtime_path_deps {
                out.push_str(&format!("                    pkgs.{dep}\n"));
            }
            out.push_str("                  ]\n                }");
        }
        if cli.cue_module.is_some() {
            out.push_str(&format!(
                " \\\n                --set SHAKA_CUE_MODULE_DIR {CUE_BUNDLE_DIR}"
            ));
        }
        out.push_str("\n            '';\n");
    }

    out.push_str("          };\n        }\n      );\n\n");
    out
}

/// `apps.default` is emitted whenever `packages.default` is emitted —
/// it's a one-liner that makes `nix run ./<project>` work, with no
/// downside. The current `tools/claude-hooks` flake omits `apps`; the
/// generator gains it (semantic equivalence covers cosmetic additions
/// that don't change consumer behavior, per #611).
fn render_apps(cli: &CliMeta) -> String {
    let bin = &cli.binary_name;
    format!(
        "      apps = forEachSupportedSystem (\n        {{ system, ... }}:\n        {{\n          default = {{\n            type = \"app\";\n            program = \"${{self.packages.${{system}}.default}}/bin/{bin}\";\n          }};\n        }}\n      );\n\n"
    )
}

fn render_devshell(cli: &CliMeta) -> String {
    let mut out = String::new();
    out.push_str("      devShells = forEachSupportedSystem (\n");
    out.push_str("        { pkgs, ... }:\n");
    out.push_str("        {\n");
    out.push_str("          default = pkgs.mkShell {\n");
    out.push_str("            packages = [\n");
    out.push_str("              (rustToolchain pkgs)\n");
    for pkg in &cli.extra_dev_shell_packages {
        out.push_str(&format!("              pkgs.{pkg}\n"));
    }
    out.push_str("            ]\n");
    out.push_str("            ++ (workflowPackages pkgs)\n");
    out.push_str(
        "            ++ pkgs.lib.optional pkgs.stdenv.hostPlatform.isLinux pkgs.cargo-llvm-cov;\n",
    );

    if cli.shell_completions {
        let bin = &cli.binary_name;
        out.push_str(&format!(
            "            shellHook = ''\n              if command -v {bin} &>/dev/null; then\n                _completions_dir=\"''${{XDG_CACHE_HOME:-$HOME/.cache}}/kolohelios-completions/{bin}\"\n                mkdir -p \"$_completions_dir\"\n                {bin} completions zsh > \"$_completions_dir/_{bin}\" 2>/dev/null\n                FPATH=\"$_completions_dir:$FPATH\"\n                unset _completions_dir\n              fi\n            '';\n"
        ));
    }

    out.push_str("          };\n        }\n      );\n");
    out
}

/// Compose a rust-worker flake. Shares the rust-cli inputs
/// (kolohelios-nix + nixpkgs + rust-overlay) but the output is
/// devShell-only: workers build to wasm via `worker-build`, not
/// `buildRustPackage`, so there's no `packages`/`apps` and no
/// `rustPlatform`. The toolchain adds the `wasm32-unknown-unknown`
/// target; the devShell carries a fixed base (`wrangler`, a
/// nixpkgs-pinned `worker-build`, plus `pkg-config` and `openssl` for
/// the wasm-bindgen / wasm-opt downloads `worker-build` runs), the
/// `~/.cargo/bin` PATH `shellHook`, and any `extra_dev_shell_packages`.
///
/// When `consumes_shaka` is set the flake also pulls a FlakeHub-built
/// `shaka` into the devShell and PATH-prepends it ahead of the
/// `workflowPackages` shim — see `render_worker_inputs` /
/// `render_worker_devshell` for why external consumers need it.
fn render_worker_flake(name: &str, worker: &WorkerMeta) -> String {
    let description = worker.description.as_deref().unwrap_or(name);
    let mut out = String::with_capacity(2048);
    out.push_str(HEADER);
    out.push_str(&format!("{{\n  description = \"{description}\";\n\n"));
    out.push_str(&render_worker_inputs(worker.consumes_shaka));
    out.push_str("\n  outputs =\n");
    out.push_str(&render_worker_output_header(worker.consumes_shaka));
    out.push_str("    in\n    {\n");
    out.push_str(&render_worker_devshell(
        &worker.extra_dev_shell_packages,
        worker.consumes_shaka,
    ));
    out.push_str("\n      formatter = kolohelios-nix.formatter;\n    };\n");
    out.push_str("}\n");
    out
}

/// Inputs for a worker flake. Default is the shared rust `INPUTS`
/// (kolohelios-nix + nixpkgs + rust-overlay). With `consumes_shaka`,
/// splice a `shaka` FlakeHub input in before the closing brace, pinned
/// to follow this flake's `kolohelios-nix` so its nixpkgs/rust-overlay
/// closure dedups against ours in `flake.lock`.
fn render_worker_inputs(consumes_shaka: bool) -> String {
    if !consumes_shaka {
        return INPUTS.to_string();
    }
    let base = INPUTS
        .strip_suffix("  };\n")
        .expect("INPUTS ends with a closing brace line");
    format!(
        "{base}    shaka = {{\n      url = \"https://flakehub.com/f/kolohelios/shaka/*.tar.gz\";\n      inputs.kolohelios-nix.follows = \"kolohelios-nix\";\n    }};\n  }};\n"
    )
}

/// `outputs` header for a worker flake. With `consumes_shaka`, add
/// `shaka` to the destructured inputs so the devShell `shellHook` can
/// reference `shaka.packages.${system}.default`.
fn render_worker_output_header(consumes_shaka: bool) -> String {
    if !consumes_shaka {
        return WORKER_OUTPUT_HEADER.to_string();
    }
    WORKER_OUTPUT_HEADER.replace(
        "      rust-overlay,\n",
        "      rust-overlay,\n      shaka,\n",
    )
}

/// Like `OUTPUT_HEADER` but tailored for workers: the toolchain gains
/// the `wasm32-unknown-unknown` target (so `cargo check --target
/// wasm32-unknown-unknown` and `worker-build` find the stdlib), and
/// `rustPlatform` is omitted since workers never call `buildRustPackage`.
const WORKER_OUTPUT_HEADER: &str = r#"    {
      self,
      kolohelios-nix,
      nixpkgs,
      rust-overlay,
      ...
    }:
    let
      inherit (kolohelios-nix.lib) supportedSystems workflowPackages;

      forEachSupportedSystem =
        f:
        nixpkgs.lib.genAttrs supportedSystems (
          system:
          f {
            inherit system;
            pkgs = import nixpkgs {
              inherit system;
              config.allowUnfree = true;
              overlays = [ rust-overlay.overlays.default ];
            };
          }
        );

      rustToolchain =
        pkgs:
        pkgs.rust-bin.stable."1.95.0".minimal.override {
          extensions = [
            "clippy"
            "rustfmt"
            "rust-src"
            "rust-analyzer"
            "llvm-tools-preview"
          ];
          targets = [ "wasm32-unknown-unknown" ];
        };
"#;

/// Devshell block for worker flakes. Fixed base — the worker toolchain,
/// `worker-build`, `pkg-config`, `openssl` — then any
/// `extra_dev_shell_packages`, then `workflowPackages` and the Linux-only
/// `wrangler` and `cargo-llvm-cov`, closing with the `~/.cargo/bin` PATH
/// `shellHook` (appended, not prepended, so a runner's rustup `cargo`
/// doesn't shadow nix's toolchain). `worker-build` is pinned via nixpkgs
/// rather than `cargo install`ed at runtime so its wasm-bindgen minimum
/// can't drift by runner cache (#864).
///
/// `wrangler` is gated to Linux (`lib.optional isLinux`) because its
/// nixpkgs derivation has no darwin binary substitute and source-builds
/// deterministically fail on darwin (EBADF in tsup's DTS step), which
/// would gate the whole shell — `shaka`/`cargo`/`worker-build` never reach
/// PATH. It's only needed at deploy time, and `cf-deploy.yml` runs on
/// `ubuntu-latest` via `nix develop . --command`, so it must stay in the
/// **default** shell on Linux (a separate deploy shell breaks CI verify).
/// See #877.
///
/// With `consumes_shaka`, the devShell function destructures `system`
/// (needed to index `shaka.packages.${system}`) and the `shellHook`
/// PATH-prepends the FlakeHub `shaka` binary ahead of the
/// `workflowPackages` shim, which can't resolve a `shaka` outside the
/// monorepo. The prepend lands before the `~/.cargo/bin` append so the
/// real binary wins.
fn render_worker_devshell(extra_dev_shell_packages: &[String], consumes_shaka: bool) -> String {
    let mut out = String::new();
    out.push_str("      devShells = forEachSupportedSystem (\n");
    if consumes_shaka {
        out.push_str("        { pkgs, system, ... }:\n");
    } else {
        out.push_str("        { pkgs, ... }:\n");
    }
    out.push_str("        {\n");
    out.push_str("          default = pkgs.mkShell {\n");
    out.push_str("            packages = [\n");
    out.push_str("              (rustToolchain pkgs)\n");
    out.push_str("              pkgs.worker-build\n");
    out.push_str("              pkgs.pkg-config\n");
    out.push_str("              pkgs.openssl\n");
    for pkg in extra_dev_shell_packages {
        out.push_str(&format!("              pkgs.{pkg}\n"));
    }
    out.push_str("            ]\n");
    out.push_str("            ++ (workflowPackages pkgs)\n");
    out.push_str(
        "            ++ pkgs.lib.optional pkgs.stdenv.hostPlatform.isLinux pkgs.wrangler\n",
    );
    out.push_str(
        "            ++ pkgs.lib.optional pkgs.stdenv.hostPlatform.isLinux pkgs.cargo-llvm-cov;\n",
    );
    out.push_str("\n            shellHook = ''\n");
    if consumes_shaka {
        out.push_str(
            "              export PATH=\"${shaka.packages.${system}.default}/bin:$PATH\"\n",
        );
    }
    out.push_str("              export PATH=\"$PATH:$HOME/.cargo/bin\"\n");
    out.push_str("            '';\n");
    out.push_str("          };\n        }\n      );\n");
    out
}

